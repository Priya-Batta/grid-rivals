create table if not exists public.grid_rivals_game_runs (
  run_id uuid primary key default pg_catalog.gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  game_mode text not null check (game_mode in ('easy', 'medium', 'hard', 'daily')),
  difficulty text not null check (difficulty in ('easy', 'medium', 'hard')),
  seed bigint not null check (seed between 1 and 2147483646),
  rules_version integer not null check (rules_version > 0),
  rng_version integer not null check (rng_version > 0),
  daily_date date,
  started_at timestamptz not null default pg_catalog.now(),
  expires_at timestamptz not null,
  consumed_at timestamptz,
  final_result jsonb,
  score_id uuid references public.grid_rivals_scores (id) on delete restrict,
  constraint grid_rivals_game_run_mode_matches_difficulty check (
    (game_mode = 'daily' and difficulty = 'medium')
    or (game_mode <> 'daily' and game_mode = difficulty)
  ),
  constraint grid_rivals_game_run_daily_date check (
    (
      game_mode = 'daily'
      and daily_date is not null
      and seed = pg_catalog.to_char(daily_date, 'YYYYMMDD')::bigint
    )
    or (game_mode <> 'daily' and daily_date is null)
  ),
  constraint grid_rivals_game_run_expiry check (expires_at > started_at),
  constraint grid_rivals_game_run_consumption check (
    (consumed_at is null and final_result is null and score_id is null)
    or (
      consumed_at is not null
      and pg_catalog.jsonb_typeof(final_result) = 'object'
      and score_id is not null
    )
  )
