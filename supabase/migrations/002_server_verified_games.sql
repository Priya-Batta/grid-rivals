create or replace function public.finalize_grid_rivals_run(
  p_run_id uuid,
  p_score integer,
  p_final_status text,
  p_moves_played integer,
  p_moves_remaining integer,
  p_tiles_claimed integer
)
returns table (
  accepted boolean,
  duplicate boolean,
  score_id uuid,
  total_xp bigint,
  player_level integer
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_run public.grid_rivals_game_runs%rowtype;
  v_progress public.grid_rivals_player_progress%rowtype;
  v_score_id uuid;
  v_max_tile_value integer;
  v_max_score integer;
  v_max_moves integer;
  v_games_completed bigint;
  v_tiles_claimed bigint;
  v_best_game_score integer;
  v_daily_completed bigint;
  v_daily_streak bigint;
  v_last_daily_date date;
  v_daily_bonus_eligible boolean := false;
  v_game_xp bigint;
  v_achievement_xp bigint;
  v_total_xp bigint;
  v_remaining_xp bigint;
  v_player_level integer;
begin
  if auth.role() is distinct from 'service_role' then
    raise exception 'Server role required';
  end if;

  select run_row.* into v_run
  from public.grid_rivals_game_runs as run_row
  where run_row.run_id = p_run_id
  for update;

  if not found then
    raise exception 'Game run was not found';
  end if;
  if v_run.consumed_at is not null then
    select progress_row.* into v_progress
    from public.grid_rivals_player_progress as progress_row
    where progress_row.user_id = v_run.user_id;

    return query
    select false, true, v_run.score_id, v_progress.total_xp, v_progress.player_level;
    return;
  end if;

  if v_run.expires_at <= pg_catalog.now() then
    raise exception 'Game run has expired';
  end if;
  if v_run.rules_version <> 1 or v_run.rng_version <> 1 then
    raise exception 'Unsupported game rules version';
  end if;
  if v_run.game_mode = 'daily'
    and v_run.daily_date <> (pg_catalog.now() at time zone 'UTC')::date then
    raise exception 'Daily game run is no longer current';
  end if;
  if p_score is null or p_score < 0 or p_score % 10 <> 0 then
    raise exception 'Invalid verified score; score must be a non-negative multiple of 10';
  end if;

  v_max_tile_value := case v_run.difficulty
    when 'easy' then 3
    when 'medium' then 3
    when 'hard' then 5
  end;
  v_max_score := (200 - 10) + (v_max_tile_value * 10);
  v_max_moves := case v_run.difficulty
    when 'easy' then 18
    when 'medium' then 12
    when 'hard' then 8
  end;

  if p_score > v_max_score then
    raise exception 'Verified score is outside the difficulty range';
  end if;
  if p_moves_played is null or p_moves_remaining is null
    or p_moves_played < 1 or p_moves_played > v_max_moves
    or p_moves_remaining < 0
    or p_moves_played + p_moves_remaining <> v_max_moves then
    raise exception 'Invalid final move counts';
  end if;
  if p_tiles_claimed is null or p_tiles_claimed <> p_moves_played then
    raise exception 'Tile claims do not match the move transcript';
  end if;
  if p_final_status is null
    or p_final_status not in ('won', 'lost')
    or (p_score >= 200 and p_final_status <> 'won')
    or (p_score < 200 and (p_moves_remaining <> 0 or p_final_status <> 'lost')) then
    raise exception 'Game result is not terminal under the current rules';
  end if;

  insert into public.grid_rivals_profiles as profile_row (user_id, display_name)
  values (
    v_run.user_id,
    'RIVAL-' || pg_catalog.upper(pg_catalog.substr(pg_catalog.replace(v_run.user_id::text, '-', ''), 1, 6))
  )
  on conflict on constraint grid_rivals_profiles_pkey do nothing;

  insert into public.grid_rivals_player_progress as progress_row (user_id)
  values (v_run.user_id)
  on conflict on constraint grid_rivals_player_progress_pkey do nothing;

  select progress_row.* into v_progress
  from public.grid_rivals_player_progress as progress_row
  where progress_row.user_id = v_run.user_id
  for update;

  insert into public.grid_rivals_scores as score_row (
    user_id, game_id, score, game_mode, difficulty, achieved_at, is_verified
  )
  values (
    v_run.user_id,
    v_run.run_id,
    p_score,
    v_run.game_mode,
    v_run.difficulty,
    pg_catalog.now(),
    true
  )
  on conflict on constraint grid_rivals_unique_game_per_player do nothing
  returning score_row.id into v_score_id;

  if v_score_id is null then
    raise exception 'A score already exists for this game run';
  end if;

  v_games_completed := v_progress.games_completed + 1;
  v_tiles_claimed := v_progress.tiles_claimed + p_tiles_claimed;
  v_best_game_score := case
    when p_score > v_progress.best_game_score then p_score
    else v_progress.best_game_score
  end;
  v_daily_completed := v_progress.daily_challenges_completed;
  v_daily_streak := v_progress.current_daily_streak;
  v_last_daily_date := v_progress.last_daily_date;

  if v_run.game_mode = 'daily'
    and v_last_daily_date is distinct from v_run.daily_date then
    v_daily_bonus_eligible := true;
    v_daily_completed := v_daily_completed + 1;
    if v_last_daily_date is not null
      and v_run.daily_date = v_last_daily_date + 1 then
      v_daily_streak := v_daily_streak + 1;
    else
      v_daily_streak := 1;
    end if;
    v_last_daily_date := v_run.daily_date;
  end if;

  update public.grid_rivals_player_progress as progress_row
  set games_completed = v_games_completed,
      tiles_claimed = v_tiles_claimed,
      best_game_score = v_best_game_score,
      daily_challenges_completed = v_daily_completed,
      current_daily_streak = v_daily_streak,
      last_daily_date = v_last_daily_date,
      updated_at = pg_catalog.now()
  where progress_row.user_id = v_run.user_id
  returning progress_row.* into v_progress;

  v_game_xp := 20 + (p_score / 10)
    + case
        when v_run.game_mode = 'daily' and v_daily_bonus_eligible then 40
        else 0
      end;

  with eligible_awards (achievement_id, reward_xp, is_eligible) as (
    values
      ('first-victory'::text, 50, v_games_completed >= 1 and p_final_status = 'won'),
      ('territory-beginner'::text, 40, v_tiles_claimed >= 10),
      ('territory-master'::text, 100, v_tiles_claimed >= 50),
      ('high-scorer'::text, 80, v_best_game_score >= 200),
      ('champion'::text, 150, v_best_game_score >= 240),
      ('daily-player'::text, 60, v_daily_completed >= 3),
      ('streak-master'::text, 120, v_daily_streak >= 7),
      ('perfect-strategist'::text, 90, p_final_status = 'won' and p_moves_remaining > 0)
  ), inserted_awards as (
    insert into public.grid_rivals_achievement_awards as award_row (
      user_id, achievement_id, xp_awarded
    )
    select v_run.user_id, eligible_awards.achievement_id, eligible_awards.reward_xp
    from eligible_awards
    where eligible_awards.is_eligible
    on conflict on constraint grid_rivals_achievement_awards_pkey do nothing
    returning award_row.xp_awarded
  )
  select coalesce(pg_catalog.sum(inserted_awards.xp_awarded), 0)::bigint
  into v_achievement_xp
  from inserted_awards;

  v_total_xp := v_progress.total_xp + v_game_xp + v_achievement_xp;
  v_remaining_xp := v_total_xp;
  v_player_level := 1;

  while v_player_level < 10000
    and v_remaining_xp >= (v_player_level * 100) loop
    v_remaining_xp := v_remaining_xp - (v_player_level * 100);
    v_player_level := v_player_level + 1;
  end loop;

  update public.grid_rivals_player_progress as progress_row
  set total_xp = v_total_xp,
      player_level = v_player_level,
      updated_at = pg_catalog.now()
  where progress_row.user_id = v_run.user_id
  returning progress_row.* into v_progress;

  update public.grid_rivals_profiles as profile_row
  set player_level = v_progress.player_level,
      updated_at = pg_catalog.now()
  where profile_row.user_id = v_run.user_id;

  update public.grid_rivals_game_runs as run_row
  set consumed_at = pg_catalog.now(),
      final_result = pg_catalog.jsonb_build_object(
        'score', p_score,
        'status', p_final_status,
        'moves_played', p_moves_played,
        'moves_remaining', p_moves_remaining,
        'tiles_claimed', p_tiles_claimed,
        'rules_version', v_run.rules_version,
        'rng_version', v_run.rng_version
      ),
      score_id = v_score_id
  where run_row.run_id = v_run.run_id;

  return query
  select true, false, v_score_id, v_progress.total_xp, v_progress.player_level;
end;
$$;

create or replace function public.grid_rivals_ranked_scores(
  p_period text,
  p_difficulty text
)
returns table (
  rank bigint,
  user_id uuid,
  display_name text,
  score integer,
  player_level integer,
  game_mode text,
  achieved_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if p_period is null or p_period not in ('all', 'today', 'week') then
    raise exception 'Invalid leaderboard period';
  end if;
  if p_difficulty is null or p_difficulty not in ('all', 'easy', 'medium', 'hard') then
    raise exception 'Invalid leaderboard difficulty';
  end if;

  return query
  with filtered_scores as (
    select score_row.user_id, profile_row.display_name, progress_row.player_level,
      score_row.score, score_row.game_mode, score_row.achieved_at, score_row.id
    from public.grid_rivals_scores as score_row
    join public.grid_rivals_profiles as profile_row
      on profile_row.user_id = score_row.user_id
    join public.grid_rivals_player_progress as progress_row
      on progress_row.user_id = score_row.user_id
    where score_row.is_verified
      and (p_difficulty = 'all' or score_row.difficulty = p_difficulty)
      and (
        p_period = 'all'
        or (p_period = 'today' and score_row.achieved_at >=
          ((pg_catalog.now() at time zone 'UTC')::date::timestamp at time zone 'UTC'))
        or (p_period = 'week' and score_row.achieved_at >= pg_catalog.now() - interval '7 days')
      )
  ), best_per_player as (
    select distinct on (filtered_scores.user_id)
      filtered_scores.user_id, filtered_scores.display_name, filtered_scores.player_level,
      filtered_scores.score, filtered_scores.game_mode, filtered_scores.achieved_at
    from filtered_scores
    order by filtered_scores.user_id, filtered_scores.score desc,
      filtered_scores.achieved_at asc, filtered_scores.id asc
  )
  select pg_catalog.row_number() over (
      order by best_per_player.score desc, best_per_player.achieved_at asc,
        best_per_player.display_name collate "C", best_per_player.user_id
    ) as rank,
    best_per_player.user_id, best_per_player.display_name, best_per_player.score,
    best_per_player.player_level, best_per_player.game_mode, best_per_player.achieved_at
  from best_per_player
  order by best_per_player.score desc, best_per_player.achieved_at asc,
    best_per_player.display_name collate "C", best_per_player.user_id;
end;
$$;

