create or replace function public.create_grid_rivals_game_run(
  p_user_id uuid,
  p_game_mode text,
  p_difficulty text,
  p_standard_seed bigint default null
)
returns table (
  run_id uuid,
  game_mode text,
  difficulty text,
  seed bigint,
  rules_version integer,
  rng_version integer,
  daily_date date,
  started_at timestamptz,
  expires_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_started_at timestamptz;
  v_expires_at timestamptz;
  v_daily_date date;
  v_seed bigint;
  v_active_runs bigint;
  v_hourly_runs bigint;
  v_run public.grid_rivals_game_runs%rowtype;
begin
  if auth.role() is distinct from 'service_role' then
    raise exception 'Server role required';
  end if;
  if p_user_id is null or not exists (
    select 1
    from auth.users as auth_user
    where auth_user.id = p_user_id
  ) then
    raise exception 'Authenticated user was not found';
  end if;
  if p_game_mode is null or p_game_mode not in ('easy', 'medium', 'hard', 'daily') then
    raise exception 'Invalid game mode';
  end if;
  if p_difficulty is null or p_difficulty not in ('easy', 'medium', 'hard') then
    raise exception 'Invalid difficulty';
  end if;
  if (p_game_mode = 'daily' and p_difficulty <> 'medium')
    or (p_game_mode <> 'daily' and p_game_mode <> p_difficulty) then
    raise exception 'Game mode and difficulty do not match';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(p_user_id::text, 0)
  );

  v_started_at := pg_catalog.clock_timestamp();
  select pg_catalog.count(*) into v_active_runs
  from public.grid_rivals_game_runs as run_row
  where run_row.user_id = p_user_id
    and run_row.consumed_at is null
    and run_row.expires_at > v_started_at;

  if v_active_runs >= 5 then
    raise exception 'Active game run limit reached';
  end if;

  select pg_catalog.count(*) into v_hourly_runs
  from public.grid_rivals_game_runs as run_row
  where run_row.user_id = p_user_id
    and run_row.started_at > v_started_at - interval '1 hour';

  if v_hourly_runs >= 10 then
    raise exception 'Hourly game run creation limit reached';
  end if;

  if p_game_mode = 'daily' then
    if p_standard_seed is not null then
      raise exception 'Daily seed is generated by the server';
    end if;
    v_daily_date := (v_started_at at time zone 'UTC')::date;
    v_seed := pg_catalog.to_char(v_daily_date, 'YYYYMMDD')::bigint;
    v_expires_at := least(
      v_started_at + interval '15 minutes',
      (v_daily_date + 1)::timestamp at time zone 'UTC'
    );
  else
    if p_standard_seed is null
      or p_standard_seed < 1
      or p_standard_seed > 2147483646 then
      raise exception 'Invalid server-generated standard seed';
    end if;
    v_daily_date := null;
    v_seed := p_standard_seed;
    v_expires_at := v_started_at + interval '15 minutes';
  end if;

  if p_game_mode = 'daily'
    and v_expires_at < pg_catalog.clock_timestamp() + interval '60 seconds' then
    raise exception 'Less than 60 seconds remain in today''s challenge';
  end if;

  insert into public.grid_rivals_game_runs (
    user_id,
    game_mode,
    difficulty,
    seed,
    rules_version,
    rng_version,
    daily_date,
    started_at,
    expires_at
  )
  values (
    p_user_id,
    p_game_mode,
    p_difficulty,
    v_seed,
    1,
    1,
    v_daily_date,
    v_started_at,
    v_expires_at
  )
  returning * into v_run;

  return query
  select v_run.run_id, v_run.game_mode, v_run.difficulty, v_run.seed,
    v_run.rules_version, v_run.rng_version, v_run.daily_date,
    v_run.started_at, v_run.expires_at;
end;
$$;

