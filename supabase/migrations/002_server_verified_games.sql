create or replace function public.get_grid_rivals_player_summary(
  p_period text default 'all',
  p_difficulty text default 'all'
)
returns table (best_score integer, player_rank bigint, player_level integer)
language sql
security definer
set search_path = ''
as $$
  select coalesce(ranked_row.score, 0)::integer,
    ranked_row.rank,
    coalesce(progress_row.player_level, 1)::integer
  from public.grid_rivals_profiles as profile_row
  left join public.grid_rivals_player_progress as progress_row
    on progress_row.user_id = profile_row.user_id
  left join public.grid_rivals_ranked_scores(p_period, p_difficulty) as ranked_row
    on ranked_row.user_id = profile_row.user_id
  where profile_row.user_id = auth.uid();
$$;

