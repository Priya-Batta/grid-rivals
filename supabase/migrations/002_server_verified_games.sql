create or replace function public.ensure_grid_rivals_profile_v2()
returns table (user_id uuid, display_name text, player_level integer)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_profile public.grid_rivals_profiles%rowtype;
  v_progress public.grid_rivals_player_progress%rowtype;
begin
  if v_user_id is null then
    raise exception 'Authenticated user is required';
  end if;

  insert into public.grid_rivals_profiles as profile_row (user_id, display_name)
  values (
    v_user_id,
    'RIVAL-' || pg_catalog.upper(pg_catalog.substr(pg_catalog.replace(v_user_id::text, '-', ''), 1, 6))
  )
  on conflict on constraint grid_rivals_profiles_pkey do nothing;

  insert into public.grid_rivals_player_progress as progress_row (user_id)
  values (v_user_id)
  on conflict on constraint grid_rivals_player_progress_pkey do nothing;

  select profile_row.* into v_profile
  from public.grid_rivals_profiles as profile_row
  where profile_row.user_id = v_user_id;

  select progress_row.* into v_progress
  from public.grid_rivals_player_progress as progress_row
  where progress_row.user_id = v_user_id;

  update public.grid_rivals_profiles as profile_row
  set player_level = v_progress.player_level,
      updated_at = pg_catalog.now()
  where profile_row.user_id = v_user_id;

    return query
    select v_profile.user_id, v_profile.display_name, v_progress.player_level;
end;
$$;

